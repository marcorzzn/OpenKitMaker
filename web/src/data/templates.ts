export function generateUuidV4(): string {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID();
  }
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0;
    const v = c === 'x' ? r : (r & 0x3) | 0x8;
    return v.toString(16);
  });
}

/**
 * FUN-SELECT-TEMPLATE: Clones a Template into a new Kit entity with fresh UUIDv4 identifiers.
 */
export function cloneTemplateToKit(template: Template): Kit {
  const now = new Date().toISOString();
  const layers: Layer[] = template.defaultLayers.map((layerDef, idx) => ({
    ...layerDef,
    id: generateUuidV4(),
    zIndex: idx,
    properties: { ...layerDef.properties },
  }));

  return {
    id: generateUuidV4(),
    name: `${template.name}`,
    category: template.category,
    createdAt: now,
    updatedAt: now,
    templateId: template.id,
    layers,
    metadata: {
      author: 'OpenKitMaker Studio',
      version: '1.0.0',
      tags: [template.category, template.patternSummary],
      finishType: 'PRO_VAPOR',
      lightingPreset: 'studio',
      decals: [],
    },
  };
}
